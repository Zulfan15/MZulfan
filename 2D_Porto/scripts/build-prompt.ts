import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { parse } from 'yaml';
import { ProfileSchema } from '../src/lib/schema';

const profilePath = resolve(process.cwd(), 'src/data/profile.yaml');
const outputPath = resolve(process.cwd(), 'worker/generated/knowledge.ts');

const raw = parse(readFileSync(profilePath, 'utf8'));
const profile = ProfileSchema.parse(raw);

const systemKnowledge = `
You are the AI Assistant for ${profile.person.name} (${profile.person.short_name}).
Title: ${profile.person.title}
Tagline: ${profile.person.tagline}
Location: ${profile.person.location}
Email: ${profile.person.email}
Summary: ${profile.person.summary}
Currently Doing: ${profile.person.now.role} at ${profile.person.now.org} - ${profile.person.now.blurb}
Open To: ${profile.person.open_to}

Education:
${profile.education.map(e => `- ${e.degree} at ${e.school} (${e.start} to ${e.end || 'Present'}). GPA: ${e.gpa || 'N/A'}`).join('\n')}

Honors & Certifications:
${profile.honors.map(h => `- ${h.title} by ${h.issuer} (${h.date}): ${h.note || ''}`).join('\n')}

Key Projects & Missions:
${profile.missions.map(m => `
Project: ${m.title} (${m.type}) [${m.start} - ${m.end || 'Present'}]
Organization: ${m.org}
Summary: ${m.summary}
${m.objective ? `Objective: ${m.objective}` : ''}
Results:
${m.results.map(r => `  * ${r}`).join('\n')}
Tech Stack: ${m.payload.join(', ')}
`).join('\n')}

Tech Stack:
${profile.stack.map(s => `${s.category}: ${s.items.join(', ')}`).join('\n')}

Rules:
${profile.assistant.rules.map(r => `- ${r}`).join('\n')}

Frequently Asked Questions:
${profile.assistant.faq.map(f => `Q: ${f.q}\nA: ${f.a}`).join('\n\n')}
`.trim();

const outputContent = `// Auto-generated by scripts/build-prompt.ts - DO NOT EDIT MANUALLY
export const PERSONA_TWIN = ${JSON.stringify(profile.assistant.twin, null, 2)};
export const PERSONA_RECEPTION = ${JSON.stringify(profile.assistant.reception, null, 2)};
export const SUGGESTED_PROMPTS = ${JSON.stringify(profile.assistant.suggested_prompts, null, 2)};

export const SYSTEM_KNOWLEDGE = ${JSON.stringify(systemKnowledge)};
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, outputContent, 'utf8');
console.log('✅ Generated worker/generated/knowledge.ts successfully from profile.yaml');
